// Каталог вариативности. Девять осей, по каждой несколько десятков значений.
// Рецепт сказки это по одному значению с каждой оси. Библия и договор остаются те же
// (про это, со стороны, ничего страшного, инструмент, правда), меняется то, как это
// рассказано: как «Тачки» и «Душа» остаются Pixar.
//
// Значения взяты из трёх учебников редактора (Кэмпбелл, Пропп, Троттье) и записаны
// своими словами. Текст книг здесь не хранится.
//
// Поля значения:
//   id      короткий стабильный идентификатор (его запоминает браузер, чтобы не повторяться)
//   t       строка для писателя, по-русски, в повелительном наклонении
//   a       [от, до] возраст слушателя, включительно
//   r       регистры, в которых значение годится: c = смешной, t = тёплый, a = приключенческий
//   narr    'first' или 'third', если значение требует лица рассказа
//   x       идентификаторы значений с других осей, с которыми оно несовместимо
//   nt      темы досье, при которых значение не годится
//   ot      значение годится только если у запроса есть одна из этих тем
//   w       вес (по умолчанию 1)

const ALL = 'cta';
function parseAge(a) {
  if (!a || a === '*') return [3, 12];
  const [lo, hi] = String(a).split('-').map(Number);
  return [lo, hi || lo];
}
function item(id, a, t, o = {}) {
  return { id, t, a: parseAge(a), r: o.r || ALL, narr: o.narr || null, x: o.x || [], nt: o.nt || [], ot: o.ot || [], w: o.w || 1 };
}

