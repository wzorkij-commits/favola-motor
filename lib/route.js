// Бесплатный тариф Vercel пускает не больше двенадцати функций, а адресов
// у мотора пятнадцать. Поэтому соседние адреса ведут в один файл, а какой
// из них спросили — говорит метка __r, которую подставляет vercel.json.
// Снаружи, для приложения, ничего не меняется: адреса те же.
//
// Метку читаем двумя способами. Если переадресация почему-то не сработала
// и запрос пришёл по исходному адресу, имя берётся прямо из него.

export function asked(req) {
  const q = req.query && req.query.__r;
  if (q) return String(q);
  const m = String(req.url || '').match(/\/api\/([a-z-]+)/);
  return m ? m[1] : '';
}
