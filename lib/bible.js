/** Досье в виде текста для писателя и редактора. */
export function formatDossier(d = {}) {
  const tool = d.tool || {};
  const lines = [
    ['Что случилось', d.what_happened],
    ['Чего ребёнок хотел', d.wants],
    ['Что сделал', d.did],
    ['Неверный вывод', d.wrong_belief],
    ['Потребность за этим', d.need],
    ['Что показать про «ничего страшного»', (d.nothing_terrible || []).join('; ')],
    ['Детали запроса, которые обязаны быть', (d.keep_details || []).join(', ')],
    ['Инструмент', tool.name ? `${tool.name}: ${tool.how}` : ''],
    ['Ручка (произнести дословно)', tool.handle ? `«${tool.handle}»` : ''],
    ['Взгляд со стороны', d.outside],
    ['Тон', ({ comic: 'смешной', tender: 'тёплый, тихий', adventure: 'приключенческий' })[d.register] || ''],
    ['Смешное из самой ситуации', d.funny],
    ['Хочу героя (цель на сегодня)', d.goal],
    ['Надо героя (что даст инструмент)', d.core],
    ['Угол зрения на тему (в текст словами не попадает)', d.angle],
    ['Что посеять в части 1', Array.isArray(d.plant) ? d.plant.filter(Boolean).join('; ') : d.plant]
  ].filter(([, v]) => v);
  const plot = d.plot ? '\nПлан:\n' + Object.entries(d.plot).map(([k, v]) => `  Часть ${k}: ${v}`).join('\n') : '';
  return lines.map(([k, v]) => `${k}: ${v}`).join('\n') + plot;
}

// Текст рецепта восстанавливается из идентификаторов, а не берётся из того, что прислал
// браузер: клиент не может подсунуть в промпт свои слова через это поле.
function recipeOf(v) {
  const ids = v && v.recipe && v.recipe.ids;
  const r = ids ? recipeFromIds(ids) : null;
  return r ? r.text : '';
}

function varietyBlock(v = {}, child = {}, lang) {
  const parts = [];
  if (child.heroName) parts.push(`Героя зовут ${child.heroName}: имя задал родитель, оставь его.`);
  else if (v.names && v.names.length) {
    parts.push(`Имя героя: выбери одно из ${v.names.join(', ')} (подбери по полу героя из запроса). Ребёнка так не зовут: имена реальных людей из запроса не используй.`);
  }
  if (v.helper) parts.push(`Кто даёт инструмент: ${v.helper}. (Если рецепт ниже уже задаёт помощника, рецепт главнее.)`);
  const rec = recipeOf(v);
  if (rec) return parts.map(x => '— ' + x).join('\n') + '\n\n' + rec;
  if (v.form) parts.push(`Как рассказано: ${v.form}`);
  if (v.opening) parts.push(`Как начать: ${v.opening}.`);
  if (v.humor) parts.push(`Главный приём юмора: ${v.humor}.`);
  return parts.map(x => '— ' + x).join('\n');
}

